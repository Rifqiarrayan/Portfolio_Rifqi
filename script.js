// Modal Functions
let currentSlide = 0;

const defaultSlides = [
    'https://via.placeholder.com/800x400/667eea/ffffff?text=Image+1',
    'https://via.placeholder.com/800x400/764ba2/ffffff?text=Image+2',
    'https://via.placeholder.com/800x400/f093fb/ffffff?text=Image+3'
];

function populateSlider(slides = defaultSlides) {
    const slider = document.querySelector('.slider');
    if (!slider) return;

    // Build images HTML and include nav buttons
    const imagesHtml = slides.map((src, i) => `\n        <img src="${src}" class="${i===0 ? 'active' : ''}">`).join('');
    slider.innerHTML = `${imagesHtml}\n        <button class="slider-btn slider-prev" onclick="changeSlide(-1)">❮</button>\n        <button class="slider-btn slider-next" onclick="changeSlide(1)">❯</button>`;
}

function openModal(type) {
    const data = experienceData[type];
    document.getElementById('modal-title').textContent = data.title;
    document.getElementById('modal-description').innerHTML = data.description;

    // Remove any project link buttons when switching from project modal to experience modal
    const modalBody = document.querySelector('.modal-body');
    const existingLinkBtn = modalBody.querySelector('.project-link-container');
    if (existingLinkBtn) existingLinkBtn.remove();

    // populate slider with provided slides or fallback defaults
    populateSlider(data.slides || defaultSlides);

    // Populate tools
    const toolsHtml = (data.tools || []).map(tool => `<span class="modal-tool">${tool}</span>`).join('');
    document.getElementById('modal-tools').innerHTML = toolsHtml;
    document.getElementById('modal-tools-title').style.display = toolsHtml ? 'block' : 'none';

    document.getElementById('modal').style.display = 'block';
    currentSlide = 0;
    showSlide(currentSlide);
}

function openProjectModal(id) {
    const project = projectsData.find(p => p.id === id);
    document.getElementById('modal-title').textContent = project.title;
    document.getElementById('modal-description').innerHTML = project.description;

    // populate slider with provided slides or fallback defaults
    populateSlider(project.slides || defaultSlides);

    const toolsHtml = (project.tools || []).map(tool => `<span class="modal-tool">${tool}</span>`).join('');
    document.getElementById('modal-tools').innerHTML = toolsHtml;
    document.getElementById('modal-tools-title').style.display = toolsHtml ? 'block' : 'none';

    // Add GitHub, Hugging Face, or Google Drive button if link exists
    const modalBody = document.querySelector('.modal-body');
    let existingLinkBtn = modalBody.querySelector('.project-link-container');
    if (existingLinkBtn) {
        existingLinkBtn.remove();
    }
    
    if (project.githubLink || project.huggingFaceLink || project.googleDriveLink) {
        let logoSrc, buttonText, logoStyle, link;
        
        if (project.huggingFaceLink) {
            link = project.huggingFaceLink;
            logoSrc = 'https://huggingface.co/front/assets/huggingface_logo-noborder.svg';
            buttonText = 'View on Hugging Face';
            logoStyle = 'width: 24px; height: 24px;';
        } else if (project.googleDriveLink) {
            link = project.googleDriveLink;
            logoSrc = 'https://ssl.gstatic.com/docs/doclist/images/drive_2022q3_32dp.png';
            buttonText = 'View on Google Drive';
            logoStyle = 'width: 24px; height: 24px;';
        } else {
            link = project.githubLink;
            logoSrc = 'https://github.githubassets.com/images/modules/logos_page/GitHub-Mark.png';
            buttonText = 'View Project';
            logoStyle = 'width: 24px; height: 24px; filter: invert(1);';
        }
        
        const linkBtnHtml = `
            <div class="project-link-container" style="margin-top: 20px; text-align: center;">
                <a href="${link}" target="_blank" class="btn btn-primary" style="display: inline-flex; align-items: center; gap: 8px;">
                    <img src="${logoSrc}" alt="${buttonText}" style="${logoStyle}">
                    ${buttonText}
                </a>
            </div>
        `;
        modalBody.insertAdjacentHTML('beforeend', linkBtnHtml);
    }

    document.getElementById('modal').style.display = 'block';
    currentSlide = 0;
    showSlide(currentSlide);
}

function closeModal() {
    document.getElementById('modal').style.display = 'none';
}

function changeSlide(n) {
    const slides = document.querySelectorAll('.slider img');
    currentSlide += n;
    if (currentSlide >= slides.length) currentSlide = 0;
    if (currentSlide < 0) currentSlide = slides.length - 1;
    showSlide(currentSlide);
}

function showSlide(n) {
    const slides = document.querySelectorAll('.slider img');
    slides.forEach((slide, index) => {
        slide.classList.remove('active');
        if (index === n) slide.classList.add('active');
    });
}

